class LatticeIndexBoundTests(unittest.TestCase):
    def assert_error(self, text, needle, line, q=None, dim=None):
        with self.assertRaises(model.CasegenError) as raised:
            parse_source(text, q=q, dim=dim)
        message = str(raised.exception)
        self.assertIn(needle, message)
        self.assertIn(f":{line}:", message)
        return message

    def test_population_index_at_q_is_rejected(self):
        self.assert_error(
            """\
            operator probe {
              var rho: scalar
              body {
                rho = moment0(f)
                f[9] = rho
              }
            }
            """,
            "index 9 is out of range",
            5,
            q=9,
        )

    def test_array_index_at_q_is_rejected(self):
        self.assert_error(
            """\
            operator probe {
              var rho: scalar
              var feq: array
              body {
                rho = moment0(f)
                feq[9] = rho
              }
            }
            """,
            "index 9 is out of range",
            6,
            q=9,
        )

    def test_weight_index_at_q_is_rejected(self):
        self.assert_error(
            """\
            operator probe {
              var rho: scalar
              body {
                rho = w(9)
              }
            }
            """,
            "index 9 is out of range",
            4,
            q=9,
        )

    def test_feq2_index_at_q_is_rejected(self):
        self.assert_error(
            """\
            operator probe {
              var rho: scalar
              var u: vector
              var feq: array
              body {
                rho = moment0(f)
                u = moment1(f, rho)
                feq[0] = feq2(rho, u, 9)
              }
            }
            """,
            "index 9 is out of range",
            8,
            q=9,
        )

    def test_component_index_at_dim_is_rejected(self):
        self.assert_error(
            """\
            operator probe {
              var rho: scalar
              var u: vector
              body {
                u = force()
                rho = u[2]
              }
            }
            """,
            "component index 2 of vector 'u' is out of range",
            6,
            q=9,
            dim=2,
        )

