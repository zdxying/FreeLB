"""End-to-end tests for the casegen command line interface.

Run with:
    python3 -m unittest discover -s tools/casegen/tests
"""

from __future__ import annotations

import io
import os
import sys
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path
from unittest import mock

_HERE = Path(__file__).resolve().parent
_TOOL = _HERE.parent
if str(_TOOL) not in sys.path:
    sys.path.insert(0, str(_TOOL))

import casegen  # noqa: E402

REPO_ROOT = _TOOL.parent.parent

# A small cavity-style spec: it exercises every emitted file but keeps the
# driver short.  No checksum section, so no pinned floating-point baseline.
BASE = """\
[case]
name = demo
dim = 2
float = double
latset = D2Q9

[fields]
list = RHO, VELOCITY, POP

[flags]
void = 1
bulk = 2
wall = 4

[grid]
n = 8, 8
cell_len = 1
block_cell_len = 4
thread_num = 1
decompose = single

[physics]
converter = simplified
char_u = 0.1
rt = 0.56
rho_init = 1
init_u = 0, 0

[region.body]
shape = aabb
box = 0, 0, 8, 8
action = paint
flag = bulk

[region.walls]
shape = aabb
box = 0, 0, 8, 8
action = boundary
flag = wall

[tasks]
bulk = bgk
wall = normal

[schedule]
type = hidden
steps = 10
output_step = 10
tol = 0
"""

OPERATOR_SECTION = "[operators]\nbgk = ops/bgk.op\n\n"


class CliTest(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.dir = Path(self._tmp.name)
        self.spec = self.dir / "demo.case"
        self.spec.write_text(BASE, encoding="utf-8")
        self.out = self.dir / "out"

    # -- helpers -----------------------------------------------------------

    def run_cli(self, argv):
        stdout, stderr = io.StringIO(), io.StringIO()
        with redirect_stdout(stdout), redirect_stderr(stderr):
            code = casegen.main(argv)
        return code, stdout.getvalue(), stderr.getvalue()

    def generate(self, *extra):
        return self.run_cli([str(self.spec), "-o", str(self.out), *extra])

    def spec_with_operators(self) -> None:
        self.spec.write_text(
            BASE.replace("[region.body]", OPERATOR_SECTION + "[region.body]"),
            encoding="utf-8",
        )

    def write_operator(self, text: str, rel: str = "ops/bgk.op") -> Path:
        path = self.dir / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        return path

    # -- catalogue ---------------------------------------------------------

    def test_list_prints_the_catalogue_without_a_spec(self) -> None:
        code, out, err = self.run_cli(["--list"])
        self.assertEqual((code, err), (0, ""))
        for needle in (
            "D2Q9",
            "D3Q19",
            "RHO",
            "bgk",
            "normal",
            "movingwall",
            "hidden",
            "single",
            "simplified",
            "rho",
        ):
            self.assertIn(needle, out)
        # Phase 3 operators are catalogue entries now; the unimplemented
        # anti_pressure boundary must not be advertised.
        for name in ("  bgk_force  ", "  mrt  ", "  les  "):
            self.assertIn(name, out)
        self.assertNotIn("anti_pressure", out)

    # -- write, check, force ----------------------------------------------

    def test_generate_then_check_is_consistent(self) -> None:
        code, out, err = self.generate()
        self.assertEqual((code, err), (0, ""))
        self.assertIn("wrote 3 file(s)", out)

        cpp = (self.out / "demo.cpp").read_text(encoding="utf-8")
        self.assertIn("// generated by casegen from demo.case -- do not edit", cpp)
        self.assertIn("// spec sha256: ", cpp)
        self.assertIn("int main(int argc, char* argv[])", cpp)

        ini = (self.out / "demo.ini").read_text(encoding="utf-8")
        self.assertIn("[Mesh]\nNi = 8\nNj = 8", ini)
        self.assertIn("TotalStep = 10", ini)

        makefile = (self.out / "Makefile").read_text(encoding="utf-8")
        self.assertIn("\nTARGET = demo.exe\n", makefile)
        expected_root = os.path.relpath(REPO_ROOT, self.out.resolve()).replace(
            os.sep, "/"
        )
        self.assertIn(f"\nROOT := {expected_root}\n", makefile)
        self.assertIn("include $(ROOT)/make.mk", makefile)

        code, out, err = self.generate("--check")
        self.assertEqual((code, err), (0, ""))
        self.assertIn("up to date (3 file(s))", out)

    def test_check_reports_stale_and_missing_with_exit_2(self) -> None:
        code, out, err = self.generate("--check")
        self.assertEqual(code, 2)
        self.assertIn("demo.cpp: missing", err)
        self.assertFalse(self.out.exists())

        self.assertEqual(self.generate()[0], 0)

        (self.out / "Makefile").write_text("stale\n", encoding="utf-8")
        code, out, err = self.generate("--check")
        self.assertEqual(code, 2)
        self.assertIn("Makefile: differs", err)

        (self.out / "demo.ini").unlink()
        code, out, err = self.generate("--check")
        self.assertEqual(code, 2)
        self.assertIn("demo.ini: missing", err)

    def test_force_is_required_to_replace_a_hand_edit(self) -> None:
        self.assertEqual(self.generate()[0], 0)

        (self.out / "demo.cpp").write_text("hand edit\n", encoding="utf-8")
        (self.out / "Makefile").write_text("hand edit\n", encoding="utf-8")
        (self.out / "demo.ini").unlink()

        code, out, err = self.generate()
        self.assertEqual(code, 1)
        self.assertIn("demo.cpp: exists with different content", err)
        self.assertIn("refusing to overwrite", err)
        self.assertEqual(
            (self.out / "demo.cpp").read_text(encoding="utf-8"), "hand edit\n"
        )
        self.assertFalse((self.out / "demo.ini").exists())

        code, out, err = self.generate("--force")
        self.assertEqual((code, err), (0, ""))
        self.assertIn("wrote 3 file(s)", out)
        self.assertNotEqual(
            (self.out / "demo.cpp").read_text(encoding="utf-8"), "hand edit\n"
        )
        self.assertTrue((self.out / "demo.ini").is_file())

        code, out, err = self.generate("--check")
        self.assertEqual((code, err), (0, ""))

    def test_check_and_force_are_mutually_exclusive(self) -> None:
        with self.assertRaises(SystemExit) as caught:
            self.generate("--check", "--force")
        self.assertEqual(caught.exception.code, 2)

    # -- --selftest --------------------------------------------------------

    def test_selftest_adds_the_regen_rule(self) -> None:
        code, out, err = self.generate("--selftest")
        self.assertEqual((code, err), (0, ""))

        makefile = (self.out / "Makefile").read_text(encoding="utf-8")
        lines = makefile.splitlines()
        self.assertIn("all: regen", lines)
        self.assertIn(".PHONY: regen", lines)
        self.assertIn("include $(ROOT)/make.mk", lines)
        self.assertTrue(
            any(
                line.startswith("\t@python3 ") and "--check --selftest" in line
                for line in lines
            ),
            makefile,
        )
        # The drift check has to run before the build, so `all: regen` and the
        # rule must precede the include that defines `all: $(TARGET)`.
        self.assertLess(makefile.index("all: regen"), makefile.index(".PHONY: regen"))
        self.assertLess(makefile.index(".PHONY: regen"), makefile.index("regen:"))
        self.assertLess(
            makefile.index("regen:"), makefile.index("include $(ROOT)/make.mk")
        )

        code, out, err = self.generate("--check", "--selftest")
        self.assertEqual((code, err), (0, ""))
        # Without --selftest the rendered Makefile has no regen rule, so the
        # directory is correctly reported as stale.
        code, out, err = self.generate("--check")
        self.assertEqual(code, 2)
        self.assertIn("Makefile: differs", err)

    def test_selftest_can_be_set_in_the_case(self) -> None:
        self.spec.write_text(
            BASE.replace("[case]\nname = demo", "[case]\nname = demo\nselftest = 1"),
            encoding="utf-8",
        )
        code, out, err = self.generate()
        self.assertEqual((code, err), (0, ""))
        makefile = (self.out / "Makefile").read_text(encoding="utf-8")
        self.assertIn("all: regen", makefile)
        self.assertIn("--check --selftest", makefile)

    # -- optimisation level ------------------------------------------------

    def test_normal_generation_uses_native_optimisation(self) -> None:
        code, out, err = self.generate()
        self.assertEqual((code, err), (0, ""))
        lines = (self.out / "Makefile").read_text(encoding="utf-8").splitlines()
        self.assertIn("FLAGS += -O3 -march=native", lines)

        # A golden case is built exactly as pinned: --selftest keeps -O2.
        code, out, err = self.generate("--force", "--selftest")
        self.assertEqual((code, err), (0, ""))
        lines = (self.out / "Makefile").read_text(encoding="utf-8").splitlines()
        self.assertIn("FLAGS += -O2", lines)
        self.assertNotIn("FLAGS += -O3 -march=native", lines)

    # -- MPI ---------------------------------------------------------------

    def test_mpi_case_emits_the_mpi_build_and_checksum(self) -> None:
        text = BASE.replace("[case]\nname = demo", "[case]\nname = demo\nmpi = 1")
        text = text.replace("decompose = single", "decompose = auto")
        text += (
            "\n[checksum]\n"
            "enable = 1\n"
            "expect_pop_mpi = 445.5\n"
            "expect_rho_mpi = 1024.0\n"
            "tol = 1e-12\n"
        )
        self.spec.write_text(text, encoding="utf-8")
        code, out, err = self.generate()
        self.assertEqual((code, err), (0, ""))

        lines = (self.out / "Makefile").read_text(encoding="utf-8").splitlines()
        self.assertIn("CXXC := mpic++", lines)
        self.assertIn("FLAGS += -DMPI_ENABLED", lines)
        self.assertIn("FLAGS += -O3 -march=native", lines)

        cpp = (self.out / "demo.cpp").read_text(encoding="utf-8")
        self.assertIn("MPI_Allreduce", cpp)
        self.assertIn('PrintChecksum("pop inner, MPI"', cpp)
        self.assertIn('PrintChecksum("rho inner, MPI"', cpp)
        self.assertIn("constexpr double kExpectPopMpi = 445.5;", cpp)
        self.assertIn("constexpr double kExpectRhoMpi = 1024.0;", cpp)
        # The non-MPI fallback stays in the file, so it also builds without
        # -DMPI_ENABLED.
        self.assertIn('PrintChecksum("pop", pop_s);', cpp)

    def test_auto_decomposition_is_rank_independent(self) -> None:
        self.spec.write_text(
            BASE.replace("decompose = single", "decompose = auto"),
            encoding="utf-8",
        )
        code, out, err = self.generate()
        self.assertEqual((code, err), (0, ""))
        cpp = (self.out / "demo.cpp").read_text(encoding="utf-8")
        # 8 cells / block_cell_len 4 = 2x2 blocks, identical for every rank.
        self.assertIn("GeoHelper.CreateBlocks(2, 2);", cpp)
        self.assertNotIn("AdaptiveOptimization", cpp)

    def test_thread_num_other_than_one_is_rejected(self) -> None:
        text = BASE.replace("thread_num = 1", "thread_num = 2")
        self.spec.write_text(text, encoding="utf-8")
        code, out, err = self.generate()
        self.assertEqual(code, 1)
        line = text.splitlines().index("thread_num = 2") + 1
        self.assertIn(f"{self.spec}:{line}:", err)
        self.assertIn("OpenMP is not wired; set thread_num = 1", err)

    def test_mpi_and_cuda_cannot_share_a_makefile(self) -> None:
        text = BASE.replace(
            "[case]\nname = demo", "[case]\nname = demo\nmpi = 1\ncuda = 1"
        )
        self.spec.write_text(text, encoding="utf-8")
        code, out, err = self.generate()
        self.assertEqual(code, 1)
        self.assertIn("mpic++ / nvcc", err)

    def test_mpi_requires_auto_decomposition(self) -> None:
        text = BASE.replace("[case]\nname = demo", "[case]\nname = demo\nmpi = 1")
        self.spec.write_text(text, encoding="utf-8")
        code, out, err = self.generate()
        self.assertEqual(code, 1)
        self.assertIn("decompose = auto", err)

    # -- [operators] diagnostics ------------------------------------------

    def test_missing_operator_file_is_a_case_error(self) -> None:
        self.spec_with_operators()
        code, out, err = self.generate()
        self.assertEqual(code, 1)
        self.assertIn("cannot read", err)
        self.assertIn(str(self.dir / "ops" / "bgk.op"), err)
        self.assertIn(f"{self.spec}:1:", err)
        self.assertFalse(self.out.exists())

    def test_operator_name_mismatch_is_a_case_error(self) -> None:
        self.spec_with_operators()
        self.write_operator(
            "operator other {\n  body {\n  }\n}\n",
            rel="ops/bgk.op",
        )
        code, out, err = self.generate()
        self.assertEqual(code, 1)
        self.assertIn("declaring operator 'other'", err)
        self.assertIn(f"{self.spec}:1:", err)

    def test_operator_syntax_error_reports_file_and_line(self) -> None:
        self.spec_with_operators()
        op_path = self.write_operator(
            "operator bgk {\n"
            "  var rho: scalar\n"
            "  body {\n"
            "    rho = froce()\n"
            "  }\n"
            "}\n"
        )
        code, out, err = self.generate()
        self.assertEqual(code, 1)
        self.assertIn(f"{op_path}:4: unknown function 'froce'", err)
        self.assertFalse(self.out.exists())

    def test_custom_operator_is_emitted_and_included(self) -> None:
        self.spec_with_operators()
        bgk_op = Path(casegen.__file__).resolve().parent / "operators" / "bgk.op"
        self.write_operator(bgk_op.read_text(encoding="utf-8"))

        code, out, err = self.generate()
        self.assertEqual((code, err), (0, ""))
        header = (self.out / "operators" / "bgk.hh").read_text(encoding="utf-8")
        self.assertIn("struct Bgk {", header)
        self.assertIn("__any__ static void apply(CELL& cell)", header)
        cpp = (self.out / "demo.cpp").read_text(encoding="utf-8")
        self.assertIn('#include "operators/bgk.hh"', cpp)

        code, out, err = self.generate("--check")
        self.assertEqual((code, err), (0, ""))

    def test_custom_operator_joins_the_rho_u_pass(self) -> None:
        # bulk stays on the catalogue bgk; obstacle is a custom .op.  Both are
        # collision operators, so both need an rho/U task alias.
        bgk_op = Path(casegen.__file__).resolve().parent / "operators" / "bgk.op"
        self.write_operator(
            bgk_op.read_text(encoding="utf-8").replace(
                "operator bgk", "operator my_op"
            ),
            rel="ops/my_op.op",
        )
        text = BASE.replace(
            "[region.body]",
            "[operators]\nmy_op = ops/my_op.op\n\n[region.body]",
        )
        text = text.replace("wall = 4", "wall = 4\nobstacle = 8")
        text = text.replace(
            "[region.walls]",
            "[region.obstacle]\nshape = aabb\nbox = 2, 2, 4, 4\n"
            "action = paint\nflag = obstacle\n\n[region.walls]",
        )
        text = text.replace(
            "[tasks]\nbulk = bgk\nwall = normal",
            "[tasks]\nbulk = bgk\nobstacle = my_op\nwall = normal",
        )
        self.spec.write_text(text, encoding="utf-8")

        code, out, err = self.generate()
        self.assertEqual((code, err), (0, ""))

        cpp = (self.out / "demo.cpp").read_text(encoding="utf-8")
        collection = next(
            line
            for line in cpp.splitlines()
            if "using TaskCollectionRhoU" in line
        )
        self.assertIn("RhoUTask_0_Bulk", collection)
        self.assertIn("RhoUTask_1_Obstacle", collection)

    def test_cuda_rejects_the_smagorinsky_field(self) -> None:
        text = BASE.replace(
            "list = RHO, VELOCITY, POP",
            "list = RHO, VELOCITY, POP, SMAGORINSKY",
        )
        text = text.replace("init_u = 0, 0", "init_u = 0, 0\nsmagorinsky = 0.1")
        text = text.replace("bulk = bgk", "bulk = les")
        text = text.replace("latset = D2Q9", "latset = D2Q9\ncuda = 1")
        self.spec.write_text(text, encoding="utf-8")

        code, out, err = self.generate()
        self.assertEqual(code, 1)
        self.assertIn("cuda = 1", err)
        self.assertIn("SMAGORINSKY", err)
        self.assertIn("device field", err)

    # -- rendered path escapes --------------------------------------------

    def test_rendered_path_escape_is_rejected(self) -> None:
        def relative_escape(spec, out_dir, repo_root):
            return {"../escape.txt": "x"}

        with mock.patch.object(casegen, "_load_renderer", return_value=relative_escape):
            code, out, err = self.run_cli([str(self.spec), "-o", str(self.out)])
        self.assertEqual(code, 1)
        self.assertIn("escapes the output directory", err)
        self.assertFalse((self.dir / "escape.txt").exists())

        outside = self.dir / "outside.txt"

        def absolute_escape(spec, out_dir, repo_root):
            return {str(outside): "x"}

        with mock.patch.object(casegen, "_load_renderer", return_value=absolute_escape):
            code, out, err = self.run_cli([str(self.spec), "-o", str(self.out)])
        self.assertEqual(code, 1)
        self.assertIn("outside the output directory", err)
        self.assertFalse(outside.exists())


if __name__ == "__main__":
    unittest.main()
